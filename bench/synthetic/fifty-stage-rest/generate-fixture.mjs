#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const args = parseArgs(process.argv.slice(2));
const outDir = path.resolve(args.out ?? ".bench/fifty-stage-rest");
const stageCount = Number.parseInt(args.stages ?? "50", 10);
const profile = args.profile ?? "basic";

if (!Number.isInteger(stageCount) || stageCount <= 0) {
  throw new Error(`--stages must be a positive integer, got ${args.stages}`);
}
if (!["basic", "api", "api-compute"].includes(profile)) {
  throw new Error(`--profile must be basic, api, or api-compute, got ${profile}`);
}

await mkdir(outDir, { recursive: true });
await mkdir(path.join(outDir, "project-plan"), { recursive: true });
await mkdir(path.join(outDir, "src"), { recursive: true });
await mkdir(path.join(outDir, "inventory"), { recursive: true });

const created = new Date().toISOString();
const stageIds = Array.from({ length: stageCount }, (_, index) =>
  `stage-${String(index + 1).padStart(2, "0")}`,
);

await writeFile(path.join(outDir, "PLAN.md"), buildPlan(stageIds, created), "utf8");
await writeFile(path.join(outDir, "DIRECTIVES.md"), buildDirectives(outDir, stageCount, created, profile), "utf8");
await writeFile(path.join(outDir, "JOURNAL.md"), buildJournal(stageCount, created), "utf8");
await writeFile(path.join(outDir, "INVENTORY.md"), buildInventory(), "utf8");
await writeFile(path.join(outDir, "src", ".gitkeep"), "", "utf8");

for (const [index, stageId] of stageIds.entries()) {
  await writeFile(
    path.join(outDir, "project-plan", `${stageId}.md`),
    buildStage(stageId, index + 1, stageIds[index - 1], created, profile),
    "utf8",
  );
}

console.log(`Generated ${stageCount}-stage InfiniClaw fixture at ${outDir}`);

function buildPlan(ids, createdAt) {
  const lines = [
    "# PLAN - 50-Stage REST Synthetic",
    "schema_version: 1",
    `created: ${createdAt}`,
    `last_replanned: ${createdAt}`,
    "status: ACTIVE",
    "owner: main",
    `turn_budget_total: ${ids.length * 20}`,
    "cost_budget_usd: 25.00",
    "",
    "## Goal",
    `Seal ${ids.length} deterministic REST-style stages without losing state across compactions.`,
    "",
    "## High-Level Definition of Done",
    "- type: file_exists",
    `  path: src/${ids.at(-1)}.mjs`,
    "- type: fs_size_under",
    "  path: JOURNAL.md",
    "  max_bytes: 10000",
    "",
    "## Stages",
  ];

  for (const [index, id] of ids.entries()) {
    const depends = index === 0 ? "" : ` | depends: [${ids[index - 1]}]`;
    lines.push(`${index + 1}. ${id} | PENDING${depends}`);
  }

  lines.push(
    "",
    "## Sealed Outputs Registry",
    "# (empty)",
    "",
    "## Global Constraints",
    "- Consult INVENTORY.md before each new module.",
    "- Do not edit DIRECTIVES.md.",
    "- Keep every stage output small and mechanically verifiable.",
    "",
    "## Notes",
    "Synthetic fixture generated by bench/synthetic/fifty-stage-rest/generate-fixture.mjs.",
  );
  return `${lines.join("\n")}\n`;
}

