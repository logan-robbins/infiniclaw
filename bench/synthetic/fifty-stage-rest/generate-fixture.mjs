function buildApiVerifierCommand(outputPath, functionName, spec) {
  const script = `
import("./${outputPath}").then((m)=>{
  const handler = m.${functionName};
  if (typeof handler !== "function") process.exit(1);
  const cases = [
    ["valid", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal} } }, 200, { checksum: "${spec.stageId}:${spec.ordinal}", route: "${spec.route}" }],
    ["missing-auth", { method: "POST", path: "${spec.route}", headers: {}, body: { id: "${spec.stageId}", value: ${spec.ordinal} } }, 401, { error: "unauthorized" }],
    ["wrong-method", { method: "GET", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal} } }, 404, { error: "not_found" }],
    ["wrong-path-before-auth", { method: "POST", path: "${spec.route}/extra", headers: {}, body: { id: "${spec.stageId}", value: ${spec.ordinal} } }, 404, { error: "not_found" }],
    ["wrong-value", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: -1 } }, 400, { error: "bad_request" }],
    ["extra-body-field", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, extra: true } }, 400, { error: "bad_request" }],
  ];
  for (const [label, request, status, bodySubset] of cases) {
    const response = handler(request);
    if (response?.status !== status) {
      console.error(label + ": expected status " + status + ", got " + response?.status);
      process.exit(1);
    }
    for (const [key, value] of Object.entries(bodySubset)) {
      if (response?.body?.[key] !== value) {
        console.error(label + ": expected body." + key + " " + JSON.stringify(value) + ", got " + JSON.stringify(response?.body?.[key]));
        process.exit(1);
      }
    }
  }
}).catch(()=>process.exit(1))
`;
  return `node -e ${JSON.stringify(script.replace(/\s+/gu, " ").trim())}`;
}

function buildApiComputeVerifierCommand(outputPath, functionName, spec) {
  const script = `
import("./${outputPath}").then((m)=>{
  const handler = m.${functionName};
  if (typeof handler !== "function") process.exit(1);
  const expected = (mode, value, values) => {
    const result = mode === "sum"
      ? value + values[0] + values[1] + values[2] + ${spec.ordinal}
      : (((value * ${spec.ordinal + 3}) + values[0] - values[1] + values[2]) % ${spec.modulus} + ${spec.modulus}) % ${spec.modulus};
    return { mode, result, checksum: "${spec.stageId}:" + mode + ":" + result + ":" + (result % ${spec.checkModulus}) };
  };
  const validCases = [
    ["valid-sum", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "sum" } }, expected("sum", ${spec.ordinal}, [1, 2, 3])],
    ["valid-mix", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal + 7}, values: [${spec.ordinal + 1}, ${spec.ordinal + 4}, ${spec.ordinal + 9}], mode: "mix" } }, expected("mix", ${spec.ordinal + 7}, [${spec.ordinal + 1}, ${spec.ordinal + 4}, ${spec.ordinal + 9}])],
  ];
  for (const [label, request, expectedBody] of validCases) {
    const response = handler(request);
    if (response?.status !== 200) {
      console.error(label + ": expected status 200, got " + response?.status);
      process.exit(1);
    }
    for (const key of ["route", "id", "mode", "result", "checksum"]) {
      const expectedValue = key === "route" ? "${spec.route}" : key === "id" ? "${spec.stageId}" : expectedBody[key];
      if (response?.body?.[key] !== expectedValue) {
        console.error(label + ": expected body." + key + " " + JSON.stringify(expectedValue) + ", got " + JSON.stringify(response?.body?.[key]));
        process.exit(1);
      }
    }
  }
  const badCases = [
    ["missing-auth", { method: "POST", path: "${spec.route}", headers: {}, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "sum" } }, 401, "unauthorized"],
    ["wrong-path-before-auth", { method: "POST", path: "${spec.route}/extra", headers: {}, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "sum" } }, 404, "not_found"],
    ["wrong-method", { method: "GET", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "sum" } }, 404, "not_found"],
    ["invalid-mode", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "avg" } }, 400, "bad_request"],
    ["short-values", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2], mode: "sum" } }, 400, "bad_request"],
    ["noninteger-value", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}.5, values: [1, 2, 3], mode: "sum" } }, 400, "bad_request"],
    ["extra-body-field", { method: "POST", path: "${spec.route}", headers: { authorization: "Bearer ${spec.token}" }, body: { id: "${spec.stageId}", value: ${spec.ordinal}, values: [1, 2, 3], mode: "sum", extra: true } }, 400, "bad_request"],
  ];
  for (const [label, request, status, error] of badCases) {
    const response = handler(request);
    if (response?.status !== status || response?.body?.error !== error) {
      console.error(label + ": expected " + status + "/" + error + ", got " + response?.status + "/" + response?.body?.error);
      process.exit(1);
    }
  }
}).catch((error)=>{ console.error(error?.stack || error?.message || String(error)); process.exit(1); })
`;
  return `node -e ${JSON.stringify(script.replace(/\s+/gu, " ").trim())}`;
}

function basicFunctionName(ordinal) {
  return `stage${String(ordinal).padStart(2, "0")}`;
}

function apiFunctionName(ordinal) {
  return `handleStage${String(ordinal).padStart(2, "0")}`;
}

function yamlSingle(value) {
  return `'${value.replace(/'/gu, "''")}'`;
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--out" || arg === "--stages" || arg === "--profile") {
      const value = argv[index + 1];
      if (!value) throw new Error(`${arg} requires a value`);
      parsed[arg.slice(2)] = value;
      index += 1;
    } else {
      throw new Error(`unknown argument: ${arg}`);
    }
  }
  return parsed;
}
