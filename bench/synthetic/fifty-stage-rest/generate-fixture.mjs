function buildStage(stageId, ordinal, previousStageId, createdAt, profileName) {
  if (profileName === "api-compute") {
    return buildApiComputeStage(stageId, ordinal, previousStageId, createdAt);
  }
  if (profileName === "api") {
    return buildApiStage(stageId, ordinal, previousStageId, createdAt);
  }
  return buildBasicStage(stageId, ordinal, previousStageId, createdAt);
}

