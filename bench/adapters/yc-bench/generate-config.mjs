function escapeTomlMultiline(value) {
  return value.replace(/\\/g, "\\\\").replace(/"""/g, '\\"\\"\\"');
}

function parseArgs(argv) {
  const parsed = {};
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const value = argv[index + 1];
    if (arg === "--out") {
      if (!value) throw new Error("--out requires a value");
      parsed.out = value;
      index += 1;
      continue;
    }
    if (arg === "--max-turns") {
      if (!value) throw new Error("--max-turns requires a value");
      parsed.maxTurns = value;
      index += 1;
      continue;
    }
    if (arg === "--history-keep-rounds") {
      if (!value) throw new Error("--history-keep-rounds requires a value");
      parsed.historyKeepRounds = value;
      index += 1;
      continue;
    }
    if (arg === "--auto-advance-turns") {
      if (!value) throw new Error("--auto-advance-turns requires a value");
      parsed.autoAdvanceTurns = value;
      index += 1;
      continue;
    }
    if (arg === "--request-timeout-seconds") {
      if (!value) throw new Error("--request-timeout-seconds requires a value");
      parsed.requestTimeoutSeconds = value;
      index += 1;
      continue;
    }
    throw new Error(`unknown argument: ${arg}`);
  }
  return parsed;
}

function positiveInteger(value, name) {
  const parsed = Number(value);
  if (!Number.isInteger(parsed) || parsed <= 0) {
    throw new Error(`${name} must be a positive integer`);
  }
  return parsed;
}

function positiveNumber(value, name) {
  const parsed = Number(value);
  if (!Number.isFinite(parsed) || parsed <= 0) {
    throw new Error(`${name} must be a positive number`);
  }
  return parsed;
}
